import pino from 'pino';
import { loadConfig } from '../shared/config.js';
import { createStorage } from '../shared/storage.js';
import { SessionStore } from '../shared/session-store.js';
const cfg = loadConfig(); const log = pino({ level: 'warn' });
const store = new SessionStore(await createStorage(cfg, log));
const id = '999999999991';
await store.saveCreds(id, JSON.stringify({ hello: 'r2' }));
await store.saveMeta(id, { number: id, settings: { prefix: '!' } });
await store.putStats('selftest', { ok: 1, at: Date.now() });
const [c, m, ids, q] = [await store.loadCreds(id), await store.loadMeta(id), await store.listSessionIds(), await store.listStats()];
console.log('creds', c, '| meta', JSON.stringify(m), '| listed', ids.includes(id), '| stats', q.length);
const raw = await (store.s.inner || store.s).get(`sessions/${id}/creds.json`);
console.log('stored bytes look encrypted:', !raw.toString().includes('hello'));
await store.deleteSession(id); await store.s.del('stats/selftest.json');
console.log('after delete listed:', (await store.listSessionIds()).includes(id));
process.exit(0);
